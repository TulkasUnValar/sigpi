"""
RLS policy tests for products app.

Tests verify the existence and structure of migration 0002_rls_policies.py:
- Migration class exists in the products migrations module
- Contains a RunPython operation with reverse_code
- Depends on 0001_initial
- SQL targets all 3 product tables
- tenant_isolation + superadmin_bypass policies present for each table
- Parent table (products_researchproduct) uses direct institution_id
- Child tables (author/attachment) use a subquery via product_id
- PostgreSQL-only guard (no-op on SQLite)

The enforcement tests run on a real PostgreSQL connection assumed as the
least-privilege ``sigpi_app`` role (via the ``postgres_app_role`` fixture), so
row-level security genuinely applies. They seed one row per institution for
every protected table under a bypass context, then prove institution A's rows
are visible while institution B's stay denied, and that the superadmin bypass
reveals both.

Design reference: openspec/changes/products/design.md — RLS Policies
Pattern reference: apps/budgets/tests/test_rls.py
"""

