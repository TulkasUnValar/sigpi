def _seed_products(conn):
    """Seed one institution-A and one institution-B row per protected table.

    Every protected row is inserted under a bypass context, because
    ``sigpi_app`` cannot see or write a foreign institution's rows otherwise.
    Seeding restores the restrictive default, so each test must opt in to a
    tenant context before it reads anything.
    """
    set_rls(conn, None, bypass=True)
    inst_a = InstitutionFactory(code="PGA", name="Institution PGA")
    inst_b = InstitutionFactory(code="PGB", name="Institution PGB")
    project_a = ProjectFactory(institution=inst_a, status="aprobado")
    project_b = ProjectFactory(institution=inst_b, status="aprobado")
    product_a = ProductFactory(project=project_a)
    product_b = ProductFactory(project=project_b)
    author_a = ProductAuthorFactory(product=product_a)
    author_b = ProductAuthorFactory(product=product_b)
    attachment_a = ProductAttachmentFactory(product=product_a)
    attachment_b = ProductAttachmentFactory(product=product_b)
    set_rls(conn, None, bypass=False)
    return {
        "inst_a": inst_a,
        "product_a": product_a,
        "product_b": product_b,
        "author_a": author_a,
        "author_b": author_b,
        "attachment_a": attachment_a,
        "attachment_b": attachment_b,
    }


class TestRLSEnforcement:
    """Cross-institution isolation for every protected products table."""

    def test_cross_institution_product_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_products(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ResearchProduct, rows["product_a"].pk, rows["product_b"].pk)

    def test_cross_institution_author_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_products(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ProductAuthor, rows["author_a"].pk, rows["author_b"].pk)

    def test_cross_institution_attachment_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_products(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ProductAttachment, rows["attachment_a"].pk, rows["attachment_b"].pk)

    def test_superadmin_bypass_sees_all(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_products(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=True)
        assert_both_visible(ResearchProduct, rows["product_a"].pk, rows["product_b"].pk)
        assert_both_visible(ProductAuthor, rows["author_a"].pk, rows["author_b"].pk)
        assert_both_visible(ProductAttachment, rows["attachment_a"].pk, rows["attachment_b"].pk)
