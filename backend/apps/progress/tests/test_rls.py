"""
RLS policy tests for the progress (advances) app.

Tests verify the existence and structure of migration 0002_rls_policies.py:
- Migration class exists in the progress migrations module
- Contains a RunPython operation with reverse_code
- Depends on 0001_initial
- SQL targets all 4 progress tables
- tenant_isolation + superadmin_bypass policies present for each table
- Parent table (progress_progressreport) uses direct institution_id
- Child tables (review/document/state log) use a subquery via progress_report_id
- PostgreSQL-only guard (no-op on SQLite)

The enforcement tests run on a real PostgreSQL connection assumed as the
least-privilege ``sigpi_app`` role (via the ``postgres_app_role`` fixture), so
row-level security genuinely applies. They seed one row per institution for
the parent report and every child table under a bypass context, then prove
institution A's rows are visible while institution B's stay denied, and that
the superadmin bypass reveals both. The parent/child pair is covered together:
the child tables only resolve the session institution through their report.

Design reference: openspec/sdd/advances/design.md — RLS Policies
Pattern reference: apps/budgets/tests/test_rls.py
"""

import importlib
import inspect

from apps.institutions.tests.conftest import InstitutionFactory
from apps.progress.models import (
    ProgressDocument,
    ProgressReport,
    ProgressReview,
    ProgressStateLog,
)
from apps.progress.tests.conftest import (
    ProgressDocumentFactory,
    ProgressReportFactory,
    ProgressReviewFactory,
    ProgressStateLogFactory,
)
from tests.rls_helpers import (
    assert_both_visible,
    assert_only_a_visible,
    get_all_sql,
    get_apply_function_source,
    load_migration,
    policy_using,
    set_rls,
)

# ──────────────────────────────────────────────
# Tables that MUST have RLS policies
# ──────────────────────────────────────────────

EXPECTED_RLS_TABLES = [
    "progress_progressreport",
    "progress_progressreview",
    "progress_progressdocument",
    "progress_progressstatelog",
]

# Tables that traverse a subquery (no direct institution_id column)
CHILD_TABLES = [
    "progress_progressreview",  # via progress_report_id
    "progress_progressdocument",  # via progress_report_id
    "progress_progressstatelog",  # via progress_report_id
]

# Each child reaches the tenant through progress_report_id into the report.
CHILD_PARENT = {
    "progress_progressreview": ("progress_report_id", "progress_progressreport"),
    "progress_progressdocument": ("progress_report_id", "progress_progressreport"),
    "progress_progressstatelog": ("progress_report_id", "progress_progressreport"),
}

EXPECTED_POLICIES = [
    "tenant_isolation",
    "superadmin_bypass",
]


# ──────────────────────────────────────────────
# Test: Migration Existence and Structure
# ──────────────────────────────────────────────


class TestRLSMigrationExists:
    """Verify migration 0002 exists and has correct structure."""

    def test_migration_0002_on_disk(self, db):
        migration = load_migration("progress", "0002_rls_policies")
        assert migration is not None, (
            "Migration 0002_rls_policies not found. "
            "Expected at: apps/progress/migrations/0002_rls_policies.py"
        )

    def test_depends_on_0001(self, db):
        migration = load_migration("progress", "0002_rls_policies")
        assert migration is not None
        deps = [(app, name) for (app, name) in migration.dependencies]
        assert ("progress", "0001_initial") in deps, (
            f"Expected dependency on progress.0001_initial, got: {deps}"
        )

    def test_has_run_python_operation(self, db):
        migration = load_migration("progress", "0002_rls_policies")
        assert migration is not None
        from django.db.migrations import RunPython

        run_python_ops = [op for op in migration.operations if isinstance(op, RunPython)]
        assert len(run_python_ops) > 0, (
            "Migration 0002 must contain at least one RunPython operation"
        )

    def test_has_reverse_code(self, db):
        migration = load_migration("progress", "0002_rls_policies")
        assert migration is not None
        from django.db.migrations import RunPython

        for op in migration.operations:
            if isinstance(op, RunPython):
                assert op.reverse_code is not None, (
                    "RunPython RLS must have reverse_code for rollback"
                )


