def _seed_progress(conn):
    """Seed one institution-A and one institution-B row per protected table.

    Every protected row is inserted under a bypass context, because
    ``sigpi_app`` cannot see or write a foreign institution's rows otherwise.
    Seeding restores the restrictive default, so each test must opt in to a
    tenant context before it reads anything.
    """
    set_rls(conn, None, bypass=True)
    inst_a = InstitutionFactory(code="PGA", name="Institution PGA")
    inst_b = InstitutionFactory(code="PGB", name="Institution PGB")
    report_a = ProgressReportFactory(institution=inst_a)
    report_b = ProgressReportFactory(institution=inst_b)
    review_a = ProgressReviewFactory(progress_report=report_a)
    review_b = ProgressReviewFactory(progress_report=report_b)
    document_a = ProgressDocumentFactory(progress_report=report_a)
    document_b = ProgressDocumentFactory(progress_report=report_b)
    log_a = ProgressStateLogFactory(progress_report=report_a)
    log_b = ProgressStateLogFactory(progress_report=report_b)
    set_rls(conn, None, bypass=False)
    return {
        "inst_a": inst_a,
        "report_a": report_a,
        "report_b": report_b,
        "review_a": review_a,
        "review_b": review_b,
        "document_a": document_a,
        "document_b": document_b,
        "log_a": log_a,
        "log_b": log_b,
    }


class TestRLSEnforcement:
    """Cross-institution isolation for the report and every child table."""

    def test_cross_institution_report_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_progress(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ProgressReport, rows["report_a"].pk, rows["report_b"].pk)

    def test_cross_institution_review_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_progress(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ProgressReview, rows["review_a"].pk, rows["review_b"].pk)

    def test_cross_institution_document_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_progress(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ProgressDocument, rows["document_a"].pk, rows["document_b"].pk)

    def test_cross_institution_state_log_invisible(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_progress(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=False)
        assert_only_a_visible(ProgressStateLog, rows["log_a"].pk, rows["log_b"].pk)

    def test_superadmin_bypass_sees_all(self, postgres_app_role):
        conn = postgres_app_role
        rows = _seed_progress(conn)

        set_rls(conn, rows["inst_a"].pk, bypass=True)
        assert_both_visible(ProgressReport, rows["report_a"].pk, rows["report_b"].pk)
        assert_both_visible(ProgressReview, rows["review_a"].pk, rows["review_b"].pk)
        assert_both_visible(ProgressDocument, rows["document_a"].pk, rows["document_b"].pk)
        assert_both_visible(ProgressStateLog, rows["log_a"].pk, rows["log_b"].pk)
